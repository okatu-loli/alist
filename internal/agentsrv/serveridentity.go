package agentsrv

import (
	"crypto/ed25519"
	"crypto/rand"
	"encoding/base64"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sync"
)

// serverIdentityFileName is the file the SERVER's long-term ed25519 keypair
// is persisted under, relative to its data directory. Deliberately distinct
// from identityFileName (an AGENT's key): the two never share a directory in
// practice, but the different name makes it impossible for one to ever be
// mistaken for / loaded as the other.
const serverIdentityFileName = "agent_server_identity.json"

// ServerIdentity is the AList server's long-term ed25519 keypair for the
// reverse-connection feature (design R1). At pairing time its PUBLIC half is
// handed to an agent, which pins it; in a later wave (R2) the server signs
// the reverse WS handshake/frames with priv and the agent verifies against
// the pinned public key — the mirror image of an agent proving itself to the
// server via Identity. priv never leaves this struct / this process: it is
// never part of any wire message (only PubKeyBase64 is ever transmitted) and
// must never be logged. It lives in a SERVER-side loader here rather than
// being generated by the agent CLIENT — the agent binary never calls
// LoadOrCreateServerIdentity, so it never holds this private key.
type ServerIdentity struct {
	pub  ed25519.PublicKey
	priv ed25519.PrivateKey
}

// PubKeyBase64 returns the server's public key, base64 (std) encoded — the
// exact form delivered to an agent at pairing (PairAgentCompleteResp.
// ServerPubKey) for it to pin. Safe to transmit/log: it is the public half.
func (s *ServerIdentity) PubKeyBase64() string {
	return base64.StdEncoding.EncodeToString(s.pub)
}

// SigningKey returns the server's ed25519 PRIVATE key for in-process signing
// of the reverse-connection handshake (design R2): the server, as the dialer,
// signs its ServerHello with this key and the agent verifies against the
// public half it pinned at pairing. Exposing it does NOT violate the "priv
// never leaves this struct" contract in the type doc — that contract is about
// the key never reaching a WIRE MESSAGE or a LOG, not about server-side code
// in this process using it to sign. Callers must treat the returned key as
// sensitive: sign with it, never serialize or log it.
func (s *ServerIdentity) SigningKey() ed25519.PrivateKey {
	return s.priv
}

// serverIdentityFile is the on-disk JSON shape: raw key bytes, base64-std
// encoded — mirrors identityFile.
type serverIdentityFile struct {
	PublicKey  string `json:"public_key"`
	PrivateKey string `json:"private_key"`
}

// serverIdentityCreateMu serializes the create leg of LoadOrCreateServerIdentity
// WITHIN a process so concurrent callers converge on a single generated key:
// the first caller past the recheck generates+persists, and every other
// caller then re-reads that same file rather than each minting (and
// overwriting with) its own. Across separate PROCESSES the same convergence
// is approximated by re-reading the file after the atomic rename (below), so
// all callers return whatever key won the rename race, never a purely
// in-memory one that disagrees with what is now on disk.
var serverIdentityCreateMu sync.Mutex

// LoadOrCreateServerIdentity loads the server's ed25519 identity persisted
// under dir, or generates and persists a fresh one (crypto/ed25519 +
// crypto/rand) if none exists yet. dir is created (0700) if missing; the
// identity file is written at 0600 via the same atomic (temp-file + rename)
// write LoadOrCreateIdentity uses, so a crash mid-write never leaves a
// corrupt or briefly-world-readable key behind.
//
// A present-but-CORRUPT file is a hard error, never silently regenerated over
// — regenerating would rotate the server's identity and break every agent
// that has already pinned the old public key (fail closed). Concurrent
// creators converge: see serverIdentityCreateMu and the post-rename re-read.
func LoadOrCreateServerIdentity(dir string) (*ServerIdentity, error) {
	if err := os.MkdirAll(dir, 0700); err != nil {
		return nil, fmt.Errorf("agent: create data dir: %w", err)
	}
	path := filepath.Join(dir, serverIdentityFileName)

	if b, err := os.ReadFile(path); err == nil {
		return parseServerIdentityFile(b)
	} else if !os.IsNotExist(err) {
		return nil, fmt.Errorf("agent: read server identity file: %w", err)
	}

	serverIdentityCreateMu.Lock()
	defer serverIdentityCreateMu.Unlock()
	// Re-check under the lock: another goroutine may have created the file
	// between our miss above and acquiring the lock. If so, adopt theirs.
	if b, err := os.ReadFile(path); err == nil {
		return parseServerIdentityFile(b)
	} else if !os.IsNotExist(err) {
		return nil, fmt.Errorf("agent: read server identity file: %w", err)
	}

	pub, priv, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		return nil, fmt.Errorf("agent: generate server identity: %w", err)
	}
	if err := saveServerIdentity(path, &ServerIdentity{pub: pub, priv: priv}); err != nil {
		return nil, err
	}
	// Re-read after the atomic rename so a cross-process creator whose rename
	// won last is the identity everyone converges on, rather than returning an
	// in-memory key that may disagree with what is now on disk.
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("agent: read back server identity file: %w", err)
	}
	return parseServerIdentityFile(b)
}

func parseServerIdentityFile(b []byte) (*ServerIdentity, error) {
	var f serverIdentityFile
	if err := json.Unmarshal(b, &f); err != nil {
		return nil, fmt.Errorf("agent: parse server identity file: %w", err)
	}
	pub, err := base64.StdEncoding.DecodeString(f.PublicKey)
	if err != nil || len(pub) != ed25519.PublicKeySize {
		return nil, fmt.Errorf("agent: server identity file has a malformed public key")
	}
	priv, err := base64.StdEncoding.DecodeString(f.PrivateKey)
	if err != nil || len(priv) != ed25519.PrivateKeySize {
		return nil, fmt.Errorf("agent: server identity file has a malformed private key")
	}
	return &ServerIdentity{pub: ed25519.PublicKey(pub), priv: ed25519.PrivateKey(priv)}, nil
}

func saveServerIdentity(path string, id *ServerIdentity) error {
	f := serverIdentityFile{
		PublicKey:  base64.StdEncoding.EncodeToString(id.pub),
		PrivateKey: base64.StdEncoding.EncodeToString(id.priv),
	}
	b, err := json.MarshalIndent(f, "", "  ")
	if err != nil {
		return fmt.Errorf("agent: encode server identity: %w", err)
	}
	return atomicWriteFile(path, b, 0600)
}

// atomicWriteFile writes b to path via a temp file created in the same
// directory (so the final rename is same-filesystem/atomic) followed by a
// rename. The temp file is created with the FINAL permission mode before any
// bytes land, so sensitive content (the server's private key) is never
// briefly readable under a more permissive default mode.
//
// This is a local, unexported duplicate of internal/agent's identity.go
// helper of the same name: that one is package-private to internal/agent and
// unreachable from here after the W1 server/agent split moved this file out.
// Duplicating ~20 lines of generic file-write plumbing is simpler and less
// invasive than exporting it across the package boundary for one caller; W3
// may fold both copies into the shared proto layer if a third caller shows up.
func atomicWriteFile(path string, b []byte, perm os.FileMode) error {
	dir := filepath.Dir(path)
	tmp, err := os.CreateTemp(dir, ".tmp-*")
	if err != nil {
		return fmt.Errorf("agent: create temp file: %w", err)
	}
	tmpName := tmp.Name()
	defer os.Remove(tmpName) // no-op once the rename below succeeds
	if err := tmp.Chmod(perm); err != nil {
		tmp.Close()
		return fmt.Errorf("agent: chmod temp file: %w", err)
	}
	if _, err := tmp.Write(b); err != nil {
		tmp.Close()
		return fmt.Errorf("agent: write temp file: %w", err)
	}
	if err := tmp.Close(); err != nil {
		return fmt.Errorf("agent: close temp file: %w", err)
	}
	if err := os.Rename(tmpName, path); err != nil {
		return fmt.Errorf("agent: rename temp file: %w", err)
	}
	return nil
}

// currentServerIdentity is the process-wide server identity injection seam
// (design R1): boot (internal/bootstrap.InitServerIdentity) loads the identity
// once and installs it here via SetServerIdentity; the anonymous pairing
// handler reads it via CurrentServerIdentity to deliver ServerPubKey. Kept in
// this LOW package (imported by both bootstrap and server/handles) so
// server/handles never has to import bootstrap — the same DI shape as
// pluginproc.Manager.SetHostBuilder.
var (
	currentServerIdentityMu sync.RWMutex
	currentServerIdentity   *ServerIdentity
)

// SetServerIdentity installs the process-wide server identity (boot wiring).
// A nil argument clears it — a context that never wired one (e.g. a minimal
// boot or a unit test) leaves CurrentServerIdentity returning nil, which the
// pairing handler treats as "no server_pubkey to deliver" rather than a crash.
func SetServerIdentity(id *ServerIdentity) {
	currentServerIdentityMu.Lock()
	defer currentServerIdentityMu.Unlock()
	currentServerIdentity = id
}

// CurrentServerIdentity returns the process-wide server identity SetServerIdentity
// installed, or nil if none was wired.
func CurrentServerIdentity() *ServerIdentity {
	currentServerIdentityMu.RLock()
	defer currentServerIdentityMu.RUnlock()
	return currentServerIdentity
}
